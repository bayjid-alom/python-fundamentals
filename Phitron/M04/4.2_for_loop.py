# For loop

"""
Concept of Python range()

range() is a built-in Python function used to generate a sequence of numbers. It is commonly used with for loops.

range(start, stop, step) ✅

start → Starting number (default is 0)
stop → Ending number (not included)
step → Difference between numbers (default is 1)

"""



# print 0-9
for i in range(100):
    print("I love Python Programming.")


for i in range(6):
    print(i)


